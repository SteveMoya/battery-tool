export function gatherPackData(): PackData | null {
  const stats = getStats();
  if (!stats || !stats.s || !stats.p) return null;

  const s = stats.s;
  const p = stats.p;
  const cellNom = inpNum('c-volts', 3.6);
  const cellAh = inpNum('c-mah', 2500) / 1000;
  const cellAmp = inpNum('c-amp', 20);

  const chemId = (() => {
    const v = inp('chem-selector', '');
    if (v && v !== 'custom') {
      try { return JSON.parse(v)?.id ?? 'li-ion'; } catch { return 'li-ion'; }
    }
    return 'li-ion';
  })();
  const packIMax = cellAmp * p;
  const packAh = cellAh * p;
  const bmsRecs = recommendBms(s, chemId as BmsCellType, packIMax, packAh, getCustomBms());
  const bms = bmsRecs.length > 0 ? bmsRecs[0].bms : null;

  const cableLength = inpNum('conn-cable-length', 30);
  const appSelect = $('conn-application') as HTMLSelectElement | null;
  const application = (appSelect?.value ?? 'general') as any;
  let connRec: ConnectorRecommendation | null = null;
  try {
    connRec = recommendConnector(s, p, cellNom, cellAh, packIMax, bms, cableLength, application);
  } catch { /* no connector data */ }

  function readSafetyLevel(elId: string): string {
    const el = document.getElementById(elId);
    if (!el) return 'neutral';
    const dataLevel = el.getAttribute('data-level');
    if (dataLevel && ['green', 'yellow', 'red', 'neutral'].includes(dataLevel)) {
      return dataLevel;
    }
    const color = el.style.borderColor || el.style.color;
    if (color.includes('22c55e') || color.includes('34d399')) return 'green';
    if (color.includes('eab308') || color.includes('fbbf24')) return 'yellow';
    if (color.includes('ef4444') || color.includes('f87171')) return 'red';
    return 'neutral';
  }

  function readSafetyPct(elId: string): number {
    const el = document.getElementById(elId);
    if (!el) return 0;
    const bar = el.querySelector('.diag-bar-fill') as HTMLElement | null;
    if (bar) return parseFloat(bar.style.width) || 0;
    return 0;
  }

  const cellType = inp('cell-type', 'cylindrical');
  const isPrismatic = cellType === 'prismatic';
  const cellDiam = inpNum('c-diam', 18);
  const cellLen = inpNum(isPrismatic ? 'c-len-p' : 'c-len', 65);
  const prismW = inpNum('c-prism-w', 148);
  const prismD = inpNum('c-prism-d', 27);

  const chemName = (() => {
    const v = inp('chem-selector', '');
    if (!v || v === 'custom') return 'Custom';
    try {
      const parsed = JSON.parse(v);
      return parsed.name ?? parsed.id ?? 'Custom';
    } catch { return 'Custom'; }
  })();

  const stripW = inpNum('sim-strip-w', 7);
  const stripT = inpNum('sim-strip-t', 0.15);
  const stripMat = (() => {
    const v = inp('sim-strip-mat', '7');
    const mats: Record<string, string> = { '7': 'Nickel', '1.7': 'Copper', '14': 'Steel' };
    return mats[v] ?? 'Nickel';
  })();

  const bom = getBomData();
  const runtimeEl = $('out-sim-runtime');
  const runtime = runtimeEl?.textContent ?? '--';
  const cutoff = inpNum('sys-cutoff', 3.0);
  const effEl = $('out-sim-eff');
  const efficiency = parseFloat(effEl?.textContent ?? '0') || 0;
  const hexMode = (inputs['hex-mode'] as HTMLInputElement | null)?.checked ?? false;
  const formFactor = isPrismatic ? 'Prismatic' : 'Cylindrical';

  /* Energy density guards */
  const energy = stats.wh;
  const weight = stats.kg;
  const volume = stats.vol;

  if (!energy || !isFinite(energy)) {
    console.warn('[datasheet] Energy is zero/NaN — cannot generate datasheet');
    return null;
  }

  const energyDensityWhPerKg = (weight && isFinite(weight) && weight > 0)
    ? energy / weight
    : 'N/A';
  const energyDensityWhPerL = (volume && isFinite(volume) && volume > 0)
    ? energy / volume
    : 'N/A';

  /* Chemistry-aware maxChargeA default */
  const CHEM_CHARGE_RATE: Record<string, number> = {
    'lfp': 1.0, 'LiFePO4': 1.0,
    'nmc': 0.5, 'NMC': 0.5,
    'lto': 2.0, 'Li₄Ti₅O₁₂': 2.0,
    'na-ion': 0.5, 'Na-Ion': 0.5,
  };
  const defaultCRate = CHEM_CHARGE_RATE[chemId] ?? 0.5;

  return {
    name: stats.name || 'Battery Pack',
    model: `BCA-${s}S${p}P`,
    date: new Date().toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' }),
    nomV: stats.v ?? 0, minV: stats.vmin ?? 0, maxV: stats.vmax ?? 0,
    capacity: stats.ah ?? 0, energy: stats.wh ?? 0,
    maxDischargeA: packIMax,
    maxChargeA: parseFloat(inp('c-charge-amp', String(cellAmp * defaultCRate))),
    cRate: packAh > 0 ? packIMax / packAh : 0,
    width: stats.w ?? 0, depth: stats.d ?? 0, height: stats.h ?? 0,
    weight: stats.kg ?? 0, volume: stats.vol ?? 0,
    cellType: cellDiam > 0 ? `${cellDiam}mm` : `${prismW}×${prismD}mm`,
    cellDiameter: cellDiam, cellLength: cellLen,
    chemistry: chemName, formFactor,
    s, p, layers: stats.l ?? 0, totalCells: stats.cells ?? 0,
    gridType: hexMode ? 'Hexagonal' : 'Square',
    bmsName: bms?.name ?? 'None',
    bmsBalance: bms?.balanceType ?? '--',
    bmsSRange: bms ? `${bms.sMin}S-${bms.sMax}S` : '--',
    bmsMaxA: bms?.maxA ?? 0,
    bmsProtocol: bms?.protocol ?? '--',
    bmsSmart: bms?.smart ?? false,
    connectorName: connRec?.connector.name ?? '--',
    connectorA: connRec?.connector.continuousA ?? 0,
    wireGauge: connRec?.wireGauge.label ?? '--',
    fuseRating: connRec ? `${connRec.fuseRating}A` : '--',
    fuseType: connRec?.fuseType ?? '--',
    antiSpark: connRec?.needsAntiSpark ?? false,
    voltageDropPct: connRec?.voltageDropPct ?? 0,
    safetyNotes: connRec?.safetyNotes ?? [],
    voltageSagLevel: readSafetyLevel('safety-voltage-sag'),
    jouleHeatLevel: readSafetyLevel('safety-joule-heat'),
    ampacityLevel: readSafetyLevel('safety-ampacity'),
    packingLevel: readSafetyLevel('safety-packing'),
    globalLevel: readSafetyLevel('diag-global-status') === 'neutral' ? 'green' : readSafetyLevel('diag-global-status'),
    voltageSagPct: readSafetyPct('safety-voltage-sag'),
    jouleHeatPct: readSafetyPct('safety-joule-heat'),
    ampacityPct: readSafetyPct('safety-ampacity'),
    packingPct: readSafetyPct('safety-packing'),
    simCurrent: getLastAmps(),
    simPower: getLastWatts(),
    runtime, efficiency, cutoff,
    nickelTotal: bom.nickelMetersTotal,
    cellCount: bom.cellCount,
    stripWidth: stripW, stripThickness: stripT, stripMaterial: stripMat,
    energyDensityWhPerKg, energyDensityWhPerL,
    complianceReport: (window as any).__complianceReport ?? null,
    protectionReport: (window as any).__protectionReport ?? null,
    thermalReport: (window as any).__thermalResult ?? null,
    coolingReport: (window as any).__coolingResult ?? null,
    enclosureReport: (window as any).__enclosureResult ?? null,
    degradationReport: (window as any).__degradationResult ?? null,
  };
}

/* ─────────────────────────────────────────────
   Draw datasheet on the CURRENT page of a jsPDF instance.
   Called by both exportDatasheet() and exportPdf().
   ───────────────────────────────────────────── */

export function drawDatasheetPage(pdf: jsPDF, data: PackData): void {
  const pw = PAGE_W;
  const ph = PAGE_H;
  const mx = MARGIN;
  const my = MARGIN;
  const contentW = pw - mx * 2;
  const colGap = 8;
  const colW = (contentW - colGap) / 2;
  const kvGap = 3.8;

  /* HEADER */
  const headerH = 14;
  pdf.setFillColor(...C.headerBg);
  pdf.roundedRect(mx, my, contentW, headerH, 2, 2, 'F');
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(12);
  pdf.setTextColor(...C.headerText);
  pdf.text('BATTERY PACK TECHNICAL DATASHEET', mx + 4, my + 6);
  pdf.setFontSize(7);
  pdf.setFont('helvetica', 'normal');
  pdf.text(`${data.name}  |  ${data.model}`, mx + 4, my + 10.5);
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(7);
  pdf.text(`Date: ${data.date}`, pw - mx - 4, my + 6, { align: 'right' });
  pdf.setFont('helvetica', 'normal');
  pdf.text(`Serial: ${data.model}-${Date.now().toString(36).toUpperCase()}`, pw - mx - 4, my + 10.5, { align: 'right' });

  /* ROW 1 */
  let row1Y = my + headerH + 4;
  const row1H = 47;
  drawSection(pdf, mx, row1Y, colW, row1H, 'Electrical Specifications');
  let ky = row1Y + SECTION_H + 4;
  drawKV(pdf, mx + 3, ky, colW, 'Nominal Voltage', `${data.nomV.toFixed(1)} V`); ky += kvGap;
  drawKV(pdf, mx + 3, ky, colW, 'Voltage Range', `${data.minV.toFixed(1)} – ${data.maxV.toFixed(1)} V`); ky += kvGap;
  drawKV(pdf, mx + 3, ky, colW, 'Capacity', `${data.capacity.toFixed(2)} Ah`); ky += kvGap;
  drawKV(pdf, mx + 3, ky, colW, 'Energy', `${data.energy >= 1000 ? (data.energy / 1000).toFixed(2) + ' kWh' : Math.round(data.energy) + ' Wh'}`); ky += kvGap;
  drawKV(pdf, mx + 3, ky, colW, 'Max Discharge', `${data.maxDischargeA.toFixed(0)} A`); ky += kvGap;
  drawKV(pdf, mx + 3, ky, colW, 'Max Charge', `${data.maxChargeA.toFixed(1)} A`); ky += kvGap;
  drawKV(pdf, mx + 3, ky, colW, 'C-rate (max)', `${data.cRate.toFixed(2)}C`); ky += kvGap;
  drawKV(pdf, mx + 3, ky, colW, 'Energy Density (Wh/kg)', data.energyDensityWhPerKg === 'N/A' ? 'N/A' : `${data.energyDensityWhPerKg.toFixed(1)}`); ky += kvGap;
  drawKV(pdf, mx + 3, ky, colW, 'Energy Density (Wh/L)', data.energyDensityWhPerL === 'N/A' ? 'N/A' : `${data.energyDensityWhPerL.toFixed(1)}`);

  const col2X = mx + colW + colGap;
  drawSection(pdf, col2X, row1Y, colW, row1H, 'Physical Specifications');
  ky = row1Y + SECTION_H + 4;
  drawKV(pdf, col2X + 3, ky, colW, 'Dimensions (L×W×H)', `${data.width.toFixed(0)}×${data.depth.toFixed(0)}×${data.height.toFixed(0)} mm`); ky += kvGap;
  drawKV(pdf, col2X + 3, ky, colW, 'Weight', `${data.weight.toFixed(2)} kg`); ky += kvGap;
  drawKV(pdf, col2X + 3, ky, colW, 'Volume', `${data.volume >= 1 ? data.volume.toFixed(2) + ' L' : Math.round(data.volume * 1000) + ' mL'}`); ky += kvGap;
  drawKV(pdf, col2X + 3, ky, colW, 'Cell Type', data.formFactor); ky += kvGap;
  drawKV(pdf, col2X + 3, ky, colW, 'Cell Dimensions', data.cellType); ky += kvGap;
  drawKV(pdf, col2X + 3, ky, colW, 'Chemistry', data.chemistry); ky += kvGap;
  drawKV(pdf, col2X + 3, ky, colW, 'Total Cells', `${data.totalCells}`);

  /* ROW 2 */
  let row2Y = row1Y + row1H + 4;
  const row2H = 32;
  drawSection(pdf, mx, row2Y, colW, row2H, 'Configuration');
  ky = row2Y + SECTION_H + 4;
  drawKV(pdf, mx + 3, ky, colW, 'Series × Parallel', `${data.s}S × ${data.p}P`); ky += kvGap;
  drawKV(pdf, mx + 3, ky, colW, 'Layers', `${data.layers}`); ky += kvGap;
  drawKV(pdf, mx + 3, ky, colW, 'Grid Pattern', data.gridType); ky += kvGap;
  drawKV(pdf, mx + 3, ky, colW, 'Pack Voltage (nom)', `${data.nomV.toFixed(1)} V`); ky += kvGap;
  drawKV(pdf, mx + 3, ky, colW, 'Pack Capacity', `${data.capacity.toFixed(2)} Ah`);

  drawSection(pdf, col2X, row2Y, colW, row2H, 'Battery Management System');
  ky = row2Y + SECTION_H + 4;
  drawKV(pdf, col2X + 3, ky, colW, 'Model', data.bmsName); ky += kvGap;
  drawKV(pdf, col2X + 3, ky, colW, 'Balance Type', data.bmsBalance); ky += kvGap;
  drawKV(pdf, col2X + 3, ky, colW, 'S Range', data.bmsSRange); ky += kvGap;
  drawKV(pdf, col2X + 3, ky, colW, 'Max Current', data.bmsMaxA > 0 ? `${data.bmsMaxA}A` : '--'); ky += kvGap;
  drawKV(pdf, col2X + 3, ky, colW, 'Protocol', data.bmsProtocol);

  /* ROW 3 */
  let row3Y = row2Y + row2H + 4;
  const row3H = 36;
  drawSection(pdf, mx, row3Y, colW, row3H, 'Power Connectors & Wiring');
  ky = row3Y + SECTION_H + 4;
  drawKV(pdf, mx + 3, ky, colW, 'Main Connector', `${data.connectorName} (${data.connectorA}A)`); ky += kvGap;
  drawKV(pdf, mx + 3, ky, colW, 'Wire Gauge', data.wireGauge); ky += kvGap;
  drawKV(pdf, mx + 3, ky, colW, 'Fuse', `${data.fuseRating} ${data.fuseType}`); ky += kvGap;
  drawKV(pdf, mx + 3, ky, colW, 'Anti-spark', data.antiSpark ? 'Yes' : 'No'); ky += kvGap;
  drawKV(pdf, mx + 3, ky, colW, 'Voltage Drop', `${data.voltageDropPct.toFixed(1)}%`);

  drawSection(pdf, col2X, row3Y, colW, row3H, 'Safety Status');
  ky = row3Y + SECTION_H + 4;
  const safetyItems = [
    { label: 'Voltage Sag', level: data.voltageSagLevel },
    { label: 'Joule Heat', level: data.jouleHeatLevel },
    { label: 'Ampacity', level: data.ampacityLevel },
    { label: 'Packing Efficiency', level: data.packingLevel },
  ];
  for (const item of safetyItems) {
    drawStatusDot(pdf, col2X + 5, ky, item.level);
    pdf.setFont('helvetica', 'normal');
    pdf.setFontSize(6.5);
    pdf.setTextColor(...C.text);
    pdf.text(item.label, col2X + 8, ky);
    pdf.setFont('helvetica', 'bold');
    const lColor: RGB = item.level === 'green' ? C.green
      : item.level === 'yellow' ? C.yellow
      : item.level === 'red' ? C.red : C.textMuted;
    pdf.setTextColor(...lColor);
    pdf.text(levelLabel(item.level), col2X + colW - 5, ky, { align: 'right' });
    ky += kvGap;
  }

  /* ROW 4 */
  let row4Y = row3Y + row3H + 4;
  const row4H = 31;
  drawSection(pdf, mx, row4Y, colW, row4H, 'Simulation Results');
  ky = row4Y + SECTION_H + 4;
  drawKV(pdf, mx + 3, ky, colW, 'Load Current', `${data.simCurrent.toFixed(1)} A`); ky += kvGap;
  drawKV(pdf, mx + 3, ky, colW, 'Useful Power', `${data.simPower >= 1000 ? (data.simPower / 1000).toFixed(2) + ' kW' : Math.round(data.simPower) + ' W'}`); ky += kvGap;
  drawKV(pdf, mx + 3, ky, colW, 'Runtime', data.runtime); ky += kvGap;
  drawKV(pdf, mx + 3, ky, colW, 'Efficiency', `${data.efficiency.toFixed(1)}%`); ky += kvGap;
  drawKV(pdf, mx + 3, ky, colW, 'LVC Cutoff', `${data.cutoff.toFixed(2)} V/cell`);

  drawSection(pdf, col2X, row4Y, colW, row4H, 'Bill of Materials Summary');
  ky = row4Y + SECTION_H + 4;
  drawKV(pdf, col2X + 3, ky, colW, 'Nickel Strip (total)', `${data.nickelTotal.toFixed(2)} m`); ky += kvGap;
  drawKV(pdf, col2X + 3, ky, colW, 'Cell Count', `${data.cellCount} units`); ky += kvGap;
  drawKV(pdf, col2X + 3, ky, colW, 'Strip Config', `${data.stripWidth}×${data.stripThickness}mm ${data.stripMaterial}`); ky += kvGap;
  drawKV(pdf, col2X + 3, ky, colW, 'Packing Efficiency', `${(data.packingPct).toFixed(1)}%`);

  /* Footer on page 1 (before potential overflow sections) */
  drawFooter(pdf, data);

  /* COMPLIANCE STATUS (if available and enabled) */
  const complianceEnabled = (window as any).__complianceExportEnabled !== false;
  if (data.complianceReport && complianceEnabled) {
    const cr = data.complianceReport;
    const bottomLimit = ph - my - 10;

    const stdDefs: Array<{ id: string; name: string; color: RGB }> = [
      { id: 'IEC_62619', name: 'IEC 62619', color: [59, 130, 246] },
      { id: 'UN_38.3', name: 'UN 38.3', color: [239, 68, 68] },
      { id: 'UL_2580', name: 'UL 2580', color: [245, 158, 11] },
      { id: 'ISO_12405', name: 'ISO 12405', color: [139, 92, 246] },
      { id: 'SAE_J2464', name: 'SAE J2464', color: [236, 72, 153] },
    ];

    const activeStdDefs = stdDefs.filter(sd =>
      cr.checks.some((c: any) => c.requirement.standard === sd.id)
    );

    /* ── Overall summary box ── */
    const summaryBoxH = 12;
    let row5Y = row4Y + row4H + 4;
    if (row5Y + summaryBoxH > bottomLimit) {
      drawFooter(pdf, data);
      pdf.addPage([PAGE_W, PAGE_H], 'landscape');
      row5Y = my;
    }

    const overallColor: RGB = cr.summary.overallStatus === 'pass' ? C.green
      : cr.summary.overallStatus === 'warn' ? C.yellow
      : cr.summary.overallStatus === 'fail' ? C.red : C.textMuted;

    pdf.setFillColor(...overallColor);
    pdf.roundedRect(mx, row5Y, contentW, summaryBoxH, 2, 2, 'F');
    pdf.setFont('helvetica', 'bold');
    pdf.setFontSize(8);
    pdf.setTextColor(...C.white);
    const statusLabel = cr.summary.overallStatus === 'pass' ? 'COMPLIANT'
      : cr.summary.overallStatus === 'warn' ? 'CAUTION'
      : cr.summary.overallStatus === 'fail' ? 'NON-COMPLIANT' : 'N/A';
    pdf.text(statusLabel, mx + 5, row5Y + 7.5);
    pdf.setFontSize(7);
    pdf.text(
      `${cr.summary.pass}/${cr.summary.total} checks passed  |  PASS:${cr.summary.pass}  WARN:${cr.summary.warn}  FAIL:${cr.summary.fail}`,
      pw - mx - 5, row5Y + 7.5, { align: 'right' },
    );

    /* ── Detailed checks per standard ── */
    let ky = row5Y + summaryBoxH + 6;

    for (const std of activeStdDefs) {
      const stdChecks = cr.checks.filter((c: any) => c.requirement.standard === std.id);
      if (stdChecks.length === 0) continue;

      const fails = stdChecks.filter((c: any) => c.status === 'fail').length;
      const warns = stdChecks.filter((c: any) => c.status === 'warn').length;
      const passes = stdChecks.filter((c: any) => c.status === 'pass').length;
      const infos = stdChecks.filter((c: any) => c.status === 'info').length;

      // Height: header(8) + summary(4) + per-check(5.5 each) + padding(4)
      const sectionH = SECTION_H + 4 + stdChecks.length * 5.5 + 4;

      if (ky + sectionH > bottomLimit) {
        drawFooter(pdf, data);
        pdf.addPage([PAGE_W, PAGE_H], 'landscape');
        ky = my;
      }

      drawSection(pdf, mx, ky, contentW, sectionH, std.name);
      let sy = ky + SECTION_H + 3;

      // Standard summary line
      pdf.setFont('helvetica', 'normal');
      pdf.setFontSize(6.5);
      pdf.setTextColor(...C.textMuted);
      pdf.text(
        `PASS: ${passes}  |  WARN: ${warns}  |  FAIL: ${fails}  |  INFO: ${infos}`,
        mx + 3, sy,
      );
      sy += 4;

      // Individual checks
      for (const check of stdChecks) {
        const statusColor: RGB = check.status === 'pass' ? C.green
          : check.status === 'warn' ? C.yellow
          : check.status === 'fail' ? C.red
          : [59, 130, 246];

        // Status marker
        pdf.setFillColor(...statusColor);
        pdf.circle(mx + 4, sy - 1.2, 1.2, 'F');

        // Clause
        pdf.setFont('helvetica', 'bold');
        pdf.setFontSize(6.5);
        pdf.setTextColor(...C.text);
        pdf.text(check.requirement.clause, mx + 7, sy);

        // Description
        pdf.setFont('helvetica', 'normal');
        pdf.setTextColor(...C.textMuted);
        const descMaxW = contentW * 0.50;
        const fittedDesc = fitText(pdf, check.requirement.description, descMaxW);
        pdf.text(fittedDesc, mx + 22, sy);

        // Actual value
        pdf.setFont('helvetica', 'bold');
        pdf.setTextColor(...statusColor);
        const actualMaxW = contentW * 0.18;
        const fittedActual = fitText(pdf, check.actual, actualMaxW);
        pdf.text(fittedActual, mx + 22 + descMaxW + 2, sy);

        // Mandatory indicator
        if (check.requirement.mandatory) {
          pdf.setFont('helvetica', 'normal');
          pdf.setFontSize(5);
          pdf.setTextColor(...C.textMuted);
          pdf.text('MANDATORY', pw - mx - 5, sy, { align: 'right' });
        }

        sy += 5.5;
      }

      ky += sectionH + 3;
    }
  }

  /* PROTECTION & DISCONNECT STATUS (if available) */
  if (data.protectionReport) {
    let row6Y = (data.complianceReport && complianceEnabled) ? ky + 8 : row4Y + row4H + 4;
    const row6H = 20;
    const pr = data.protectionReport;

    if (row6Y + row6H > ph - my - 10) {
      drawFooter(pdf, data);
      pdf.addPage([PAGE_W, PAGE_H], 'landscape');
      row6Y = my;
    }

    drawSection(pdf, mx, row6Y, contentW, row6H, 'Protection & Disconnect');
    ky = row6Y + SECTION_H + 4;

    // Status
    const statusColor: RGB = pr.summary.overallStatus === 'safe' ? C.green
      : pr.summary.overallStatus === 'caution' ? C.yellow : C.red;

    pdf.setFont('helvetica', 'bold');
    pdf.setFontSize(7);
    pdf.setTextColor(...statusColor);
    const statusLabel = pr.summary.overallStatus === 'safe' ? 'SAFE'
      : pr.summary.overallStatus === 'caution' ? 'CAUTION' : 'DANGER';
    pdf.text(statusLabel, mx + 3, ky);

    pdf.setFont('helvetica', 'normal');
    pdf.setTextColor(...C.textMuted);
    pdf.text(
      `${pr.recommendations.length} component(s) recommended  |  ${pr.recommendations.filter(r => r.priority === 'required').length} required`,
      mx + 30, ky,
    );

    // List components
    ky += kvGap;
    for (const rec of pr.recommendations) {
      if (ky > ph - my - 8) break;
      const catIcon = rec.category === 'contactor' ? 'CTC'
        : rec.category === 'breaker' ? 'BRK'
        : rec.category === 'disconnect' ? 'DIS'
        : rec.category === 'precharge' ? 'PRE'
        : rec.category === 'fuse' ? 'FUS'
        : '???';
      const priorityMark = rec.priority === 'required' ? '*' : rec.priority === 'recommended' ? '-' : '';

      pdf.setFont('helvetica', 'bold');
      pdf.setFontSize(6);
      const priorityColor: RGB = rec.priority === 'required' ? C.red : rec.priority === 'recommended' ? C.yellow : C.textMuted;
      pdf.setTextColor(...priorityColor);
      pdf.text(`[${catIcon}] ${priorityMark}`, mx + 3, ky);

      pdf.setFont('helvetica', 'normal');
      pdf.setTextColor(...C.textDark);
      pdf.text(`${rec.component}: ${rec.partNumber}`, mx + 20, ky);

      pdf.setTextColor(...C.textMuted);
      pdf.text(`— ${rec.reason.substring(0, 60)}${rec.reason.length > 60 ? '…' : ''}`, mx + 90, ky);

      ky += kvGap - 0.5;
    }

    // Warnings
    if (pr.warnings.length > 0) {
      ky += 1;
      pdf.setFont('helvetica', 'bold');
      pdf.setFontSize(6);
      pdf.setTextColor(...C.red);
      for (const w of pr.warnings) {
        if (ky > ph - my - 8) break;
        pdf.text(`! ${w}`, mx + 3, ky);
        ky += kvGap - 0.5;
      }
    }
  }

  /* THERMAL ANALYSIS (if available) */
  if (data.thermalReport) {
    let row7Y = ky + 8;
    const row7H = 18;
    const tr = data.thermalReport;

    if (row7Y + row7H > ph - my - 10) {
      drawFooter(pdf, data);
      pdf.addPage([PAGE_W, PAGE_H], 'landscape');
      row7Y = my;
    }

    drawSection(pdf, mx, row7Y, contentW, row7H, 'Thermal Analysis');
    ky = row7Y + SECTION_H + 4;

    // Status
    const thermalColor: RGB = tr.level === 'green' ? C.green
      : tr.level === 'yellow' ? C.yellow : C.red;

    pdf.setFont('helvetica', 'bold');
    pdf.setFontSize(7);
    pdf.setTextColor(...thermalColor);
    const thermalLabel = tr.level === 'green' ? 'OK'
      : tr.level === 'yellow' ? 'WARM' : 'HOT';
    pdf.text(thermalLabel, mx + 3, ky);

    pdf.setFont('helvetica', 'normal');
    pdf.setTextColor(...C.textMuted);
    pdf.text(
      `Cell: ${tr.tCell.toFixed(1)}°C  |  Max: ${tr.tCellMax.toFixed(1)}°C  |  Derating: ${(tr.deratingFactor * 100).toFixed(0)}%  |  Cycles: ${tr.estimatedCycles.toLocaleString()}`,
      mx + 20, ky,
    );

    ky += kvGap;
    pdf.setFontSize(6);
    pdf.setTextColor(...C.textDark);
    pdf.text(
      `Heat: ${tr.heatGenerationW >= 100 ? Math.round(tr.heatGenerationW) : tr.heatGenerationW.toFixed(1)}W  |  Gradient: ${tr.thermalGradient.toFixed(1)}°C  |  Annual Degradation: ${tr.annualDegradation.toFixed(1)}%  |  Cooling: ${tr.coolingPowerW.toFixed(1)}W`,
      mx + 3, ky,
    );
  }

  /* COOLING SYSTEM (if available) */
  if (data.coolingReport) {
    let row8Y = ky + 8;
    const row8H = 16;
    const cr = data.coolingReport;

    if (row8Y + row8H > ph - my - 10) {
      drawFooter(pdf, data);
      pdf.addPage([PAGE_W, PAGE_H], 'landscape');
      row8Y = my;
    }

    drawSection(pdf, mx, row8Y, contentW, row8H, 'Cooling System');
    ky = row8Y + SECTION_H + 4;

    const coolColor: RGB = cr.level === 'green' ? C.green
      : cr.level === 'yellow' ? C.yellow : C.red;

    pdf.setFont('helvetica', 'bold');
    pdf.setFontSize(7);
    pdf.setTextColor(...coolColor);
    const coolLabel = cr.level === 'green' ? 'OK'
      : cr.level === 'yellow' ? 'MARGINAL' : 'INSUFFICIENT';
    pdf.text(coolLabel, mx + 3, ky);

    pdf.setFont('helvetica', 'normal');
    pdf.setTextColor(...C.textMuted);
    const methodLabel = cr.method === 'passive' ? 'Passive' : cr.method === 'air' ? 'Air Cooled' : 'Liquid Cooled';
    pdf.text(
      `${methodLabel}  |  Capacity: ${cr.coolingCapacityW.toFixed(0)}W  |  Power: ${cr.powerConsumptionW.toFixed(1)}W  |  TIM: ${cr.recommendedTim.name}`,
      mx + 25, ky,
    );

    ky += kvGap;
    pdf.setFontSize(6);
    pdf.setTextColor(...C.textDark);
    pdf.text(
      `Cell Temp: ${cr.tCellMax.toFixed(1)}°C  |  Gradient: ${cr.thermalGradient.toFixed(1)}°C${cr.method === 'air' ? `  |  Airflow: ${cr.fanCFM.toFixed(0)} CFM` : ''}${cr.method === 'liquid' ? `  |  Flow: ${cr.coolantFlowLPM.toFixed(1)} LPM` : ''}`,
      mx + 3, ky,
    );
  }

  /* ENCLOSURE DESIGN (if available) */
  if (data.enclosureReport) {
    let row9Y = ky + 8;
    const row9H = 16;
    const er = data.enclosureReport;

    if (row9Y + row9H > ph - my - 10) {
      drawFooter(pdf, data);
      pdf.addPage([PAGE_W, PAGE_H], 'landscape');
      row9Y = my;
    }

    drawSection(pdf, mx, row9Y, contentW, row9H, 'Enclosure Design');
    ky = row9Y + SECTION_H + 4;

    const encColor: RGB = er.level === 'green' ? C.green
      : er.level === 'yellow' ? C.yellow : C.red;

    pdf.setFont('helvetica', 'bold');
    pdf.setFontSize(7);
    pdf.setTextColor(...encColor);
    const encLabel = er.level === 'green' ? 'OK'
      : er.level === 'yellow' ? 'CAUTION' : 'INCOMPATIBLE';
    pdf.text(encLabel, mx + 3, ky);

    pdf.setFont('helvetica', 'normal');
    pdf.setTextColor(...C.textMuted);
    pdf.text(
      `${er.materialLabel}  |  ${er.ipLabel}  |  ${er.widthMm.toFixed(0)}×${er.depthMm.toFixed(0)}×${er.heightMm.toFixed(0)}mm  |  ${er.enclosureWeightKg.toFixed(1)}kg  |  €${er.estimatedCostEur.toFixed(0)}`,
      mx + 25, ky,
    );

    ky += kvGap;
    pdf.setFontSize(6);
    pdf.setTextColor(...C.textDark);
    pdf.text(
      `Total Weight: ${er.totalWeightKg.toFixed(1)}kg  |  Thermal R: ${er.thermalResistance.toFixed(2)}°C/W${er.material.emiShielding ? '  |  EMI Shielded' : ''}`,
      mx + 3, ky,
    );
  }

  /* DEGRADATION & CYCLE LIFE (if available) */
  if (data.degradationReport) {
    let row10Y = ky + 8;
    const row10H = 16;
    const dr = data.degradationReport;

    if (row10Y + row10H > ph - my - 10) {
      drawFooter(pdf, data);
      pdf.addPage([PAGE_W, PAGE_H], 'landscape');
      row10Y = my;
    }

    drawSection(pdf, mx, row10Y, contentW, row10H, 'Degradation & Cycle Life');
    ky = row10Y + SECTION_H + 4;

    const degColor: RGB = dr.level === 'excellent' ? C.green
      : dr.level === 'good' ? [59, 130, 246] as const
      : dr.level === 'fair' ? C.yellow : C.red;

    pdf.setFont('helvetica', 'bold');
    pdf.setFontSize(7);
    pdf.setTextColor(...degColor);
    pdf.text(dr.level.toUpperCase(), mx + 3, ky);

    pdf.setFont('helvetica', 'normal');
    pdf.setTextColor(...C.textMuted);
    pdf.text(
      `Cycles to 80%: ${dr.cyclesTo80pct.toLocaleString()}  |  Calendar: ${dr.calendarLifeYears}yr  |  Cost: €${dr.costPerCycle.toFixed(2)}/cycle`,
      mx + 25, ky,
    );

    ky += kvGap;
    pdf.setFontSize(6);
    pdf.setTextColor(...C.textDark);
    pdf.text(
      `Fade: ${dr.capacityFadePerCycle.toFixed(4)}%/√cycle  |  Total Energy: ${(dr.cyclesTo80pct * data.energy / 1000000).toFixed(0)} MWh over life`,
      mx + 3, ky,
    );
  }

  /* FOOTER */
  drawFooter(pdf, data);
}

/* ── Standalone export (menu item) ── */
export function exportDatasheet(): void {
  const data = gatherPackData();
  if (!data) return;
  const pdf = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' });
  drawDatasheetPage(pdf, data);
  const safeName = data.name.replace(/[^a-z0-9]/gi, '_').toLowerCase();
  pdf.save(`${safeName}_${data.s}S${data.p}P_datasheet.pdf`);
}

/* ── Compliance Report Export (dedicated page) ── */

export function exportComplianceReport(): void {
  const data = gatherPackData();
  if (!data) return;

  const cr = (window as any).__complianceReport;
  if (!cr) {
    alert('No compliance report available. Click "Run Compliance Check" first.');
    return;
  }

  const pdf = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  const pw = 210;
  const ph = 297;
  const mx = 15;
  const my = 15;
  const contentW = pw - mx * 2;
  const kvGap = 4.5;

  /* HEADER */
  const headerH = 18;
  pdf.setFillColor(...C.headerBg);
  pdf.roundedRect(mx, my, contentW, headerH, 2, 2, 'F');
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(14);
  pdf.setTextColor(...C.headerText);
  pdf.text('STANDARDS COMPLIANCE REPORT', mx + 5, my + 8);
  pdf.setFontSize(7);
  pdf.setFont('helvetica', 'normal');
  pdf.text(`${data.name}  |  ${data.model}`, mx + 5, my + 13.5);
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(7);
  pdf.text(`Date: ${data.date}`, pw - mx - 5, my + 8, { align: 'right' });
  pdf.setFont('helvetica', 'normal');
  pdf.text(`Serial: ${data.model}-${Date.now().toString(36).toUpperCase()}`, pw - mx - 5, my + 13.5, { align: 'right' });

  /* OVERALL STATUS */
  let ky = my + headerH + 8;
  const overallColor: RGB = cr.summary.overallStatus === 'pass' ? C.green
    : cr.summary.overallStatus === 'warn' ? C.yellow
    : cr.summary.overallStatus === 'fail' ? C.red : C.textMuted;

  pdf.setFillColor(...overallColor);
  pdf.roundedRect(mx, ky, contentW, 12, 2, 2, 'F');
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(10);
  pdf.setTextColor(...C.white);
  const statusLabel = cr.summary.overallStatus === 'pass' ? 'COMPLIANT'
    : cr.summary.overallStatus === 'warn' ? 'CAUTION'
    : cr.summary.overallStatus === 'fail' ? 'NON-COMPLIANT' : 'N/A';
  pdf.text(statusLabel, mx + 5, ky + 7.5);
  pdf.setFontSize(8);
  pdf.text(
    `${cr.summary.pass}/${cr.summary.total} checks passed`,
    pw - mx - 5, ky + 7.5, { align: 'right' },
  );

  /* PACK SUMMARY */
  ky += 18;
  drawSection(pdf, mx, ky, contentW, 16, 'Pack Configuration');
  ky += SECTION_H + 3;
  pdf.setFont('helvetica', 'normal');
  pdf.setFontSize(7);
  pdf.setTextColor(...C.textMuted);

  const packInfo = [
    `${data.s}S x ${data.p}P`,
    `${data.nomV.toFixed(1)}V nominal`,
    `${data.capacity.toFixed(2)} Ah`,
    `${data.energy >= 1000 ? (data.energy / 1000).toFixed(2) + ' kWh' : Math.round(data.energy) + ' Wh'}`,
    data.chemistry,
    data.formFactor,
  ];
  pdf.text(packInfo.join('  |  '), mx + 3, ky + 3);

  /* DETAILED CHECKS BY STANDARD */
  ky += 20;
  const standardIds: Array<{ id: string; name: string; color: RGB }> = [
    { id: 'IEC_62619', name: 'IEC 62619', color: [59, 130, 246] },
    { id: 'UN_38.3', name: 'UN 38.3', color: [239, 68, 68] },
    { id: 'UL_2580', name: 'UL 2580', color: [245, 158, 11] },
    { id: 'ISO_12405', name: 'ISO 12405', color: [139, 92, 246] },
    { id: 'SAE_J2464', name: 'SAE J2464', color: [236, 72, 153] },
  ];

  for (const std of standardIds) {
    const stdChecks = cr.checks.filter((c: any) => c.requirement.standard === std.id);
    if (stdChecks.length === 0) continue;

    const fails = stdChecks.filter((c: any) => c.status === 'fail').length;
    const warns = stdChecks.filter((c: any) => c.status === 'warn').length;
    const passes = stdChecks.filter((c: any) => c.status === 'pass').length;
    const infos = stdChecks.filter((c: any) => c.status === 'info').length;

    const sectionH = 8 + stdChecks.length * 6 + 4;
    if (ky + sectionH > ph - my - 20) {
      pdf.addPage();
      ky = my;
    }

    drawSection(pdf, mx, ky, contentW, sectionH, std.name);
    let sy = ky + SECTION_H + 3;

    // Standard summary line
    pdf.setFont('helvetica', 'normal');
    pdf.setFontSize(6.5);
    pdf.setTextColor(...C.textMuted);
    pdf.text(
      `PASS: ${passes}  |  WARN: ${warns}  |  FAIL: ${fails}  |  INFO: ${infos}`,
      mx + 3, sy,
    );
    sy += 4;

    // Individual checks
    for (const check of stdChecks) {
      const statusColor: RGB = check.status === 'pass' ? C.green
        : check.status === 'warn' ? C.yellow
        : check.status === 'fail' ? C.red
        : [59, 130, 246];

      // Status marker
      pdf.setFillColor(...statusColor);
      pdf.circle(mx + 4, sy - 1.2, 1.2, 'F');

      // Clause
      pdf.setFont('helvetica', 'bold');
      pdf.setFontSize(6.5);
      pdf.setTextColor(...C.text);
      pdf.text(check.requirement.clause, mx + 7, sy);

      // Description
      pdf.setFont('helvetica', 'normal');
      pdf.setTextColor(...C.textMuted);
      const descMaxW = contentW * 0.55;
      const fittedDesc = fitText(pdf, check.requirement.description, descMaxW);
      pdf.text(fittedDesc, mx + 22, sy);

      // Actual value
      pdf.setFont('helvetica', 'bold');
      pdf.setTextColor(...statusColor);
      const actualMaxW = contentW * 0.2;
      const fittedActual = fitText(pdf, check.actual, actualMaxW);
      pdf.text(fittedActual, mx + 22 + descMaxW + 2, sy);

      // Mandatory indicator
      if (check.requirement.mandatory) {
        pdf.setFont('helvetica', 'normal');
        pdf.setFontSize(5);
        pdf.setTextColor(...C.textMuted);
        pdf.text('MANDATORY', pw - mx - 5, sy, { align: 'right' });
      }

      sy += 5.5;
    }

    ky += sectionH + 3;
  }

  /* NOTES SECTION */
  if (ky + 30 > ph - my - 10) {
    pdf.addPage();
    ky = my;
  }

  ky += 2;
  drawSection(pdf, mx, ky, contentW, 22, 'Notes & Recommendations');
  ky += SECTION_H + 3;

  pdf.setFont('helvetica', 'normal');
  pdf.setFontSize(6.5);
  pdf.setTextColor(...C.text);

  const notes: string[] = [];
  if (cr.summary.fail > 0) {
    notes.push('- Address all FAIL items before manufacturing. Mandatory failures must be resolved for certification.');
  }
  if (cr.summary.warn > 0) {
    notes.push('- Review WARN items. These are recommendations for improved safety or performance.');
  }
  notes.push('- This report is generated for reference only. Verify compliance with your local certification authority.');
  notes.push('- Standards referenced: IEC 62619 (2022), UN 38.3 (Rev.7), UL 2580 (Ed.2), ISO 12405 (2021), SAE J2464 (2021).');

  for (const note of notes) {
    const fitted = fitText(pdf, note, contentW - 6);
    pdf.text(fitted, mx + 3, ky);
    ky += 4;
  }

  /* FOOTER */
  const footerY = ph - my - 6;
  pdf.setFont('helvetica', 'normal');
  pdf.setFontSize(5.5);
  pdf.setTextColor(...C.textMuted);
  pdf.text(
    'Generated by Battery Tool — Compliance Report',
    mx, footerY,
  );
  pdf.text(
    data.date,
    pw - mx, footerY,
    { align: 'right' },
  );
  pdf.setDrawColor(...C.sectionBorder);
  pdf.setLineWidth(0.15);
  pdf.line(mx, footerY - 3, pw - mx, footerY - 3);

  const safeName = data.name.replace(/[^a-z0-9]/gi, '_').toLowerCase();
  pdf.save(`${safeName}_${data.s}S${data.p}P_compliance.pdf`);
}
